    "4. 严禁给出正确答案或修改后的句子（哪怕一个词）——纠错由下游 grammar_tutor 节点负责。\n"
    "5. feedback 只用一句话概述错误类型，同样不含任何正确写法。\n"
    "6. 无语法错误时：has_issue=False，issues 为空列表，feedback 为空字符串。"
