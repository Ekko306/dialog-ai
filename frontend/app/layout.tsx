import type { Metadata } from "next";
import { IBM_Plex_Mono, Inter } from "next/font/google";
import { ThemeApplier } from "@/components/theme-applier";
import { TooltipProvider } from "@/components/ui/tooltip";
import "./globals.css";

const inter = Inter({
  variable: "--font-inter",
  subsets: ["latin"],
  axes: ["opsz"],
});

const ibmPlexMono = IBM_Plex_Mono({
  variable: "--font-ibm-plex-mono",
  subsets: ["latin"],
  weight: ["400", "500", "600"],
});

export const metadata: Metadata = {
  title: "assistant-ui App",
  description: "Generated by create-assistant-ui",
};

/**
 * 首屏防闪烁：在水合前把「我的-设置 → 外观模式」应用到 <html>（.dark 类）。
 * 判定规则必须与 theme-applier.tsx 的 resolveIsDark 一致，改动需两处同步。
 */
const themeInitScript = `(function(){try{var s=JSON.parse(localStorage.getItem("dialog-ai:profile:settings")||"{}");var t=s.theme==="dark"||s.theme==="light"||s.theme==="system"?s.theme:"system";var d=t==="dark"||(t==="system"&&window.matchMedia("(prefers-color-scheme: dark)").matches);var c=document.documentElement.classList;d?c.add("dark"):c.remove("dark");}catch(e){}})()`;

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html lang="en" suppressHydrationWarning>
      <body className={`${inter.variable} ${ibmPlexMono.variable} antialiased`}>
        <script dangerouslySetInnerHTML={{ __html: themeInitScript }} />
        <ThemeApplier />
        <TooltipProvider>{children}</TooltipProvider>
      </body>
    </html>
  );
}
